"""Typed extension points; the core never invents a reference or failure model."""
from typing import Protocol, Any
from fractions import Fraction
from .model import Region, Floor


class TaskAdapter(Protocol):
    def build(self, parameters: dict, implementation: dict) -> tuple[Any, Region]: ...
    def reference(self, values: dict[str,int], scale: dict) -> tuple[dict[str,int],Fraction | int]: ...
    def measure(self, circuit: Any, parameters: dict, domain: dict) -> dict: ...
    def oracle(self, circuit: Any, parameters: dict, domain: dict) -> dict: ...
    def verify(self, circuit: Any, parameters: dict, domain: dict) -> dict: ...
    def ledger(self, circuit: Any, tree: Region) -> dict: ...
    def floors(self, tree: Region) -> list[Floor]: ...
