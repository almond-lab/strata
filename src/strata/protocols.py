"""Typed extension points; the core never invents a reference or failure model."""
from typing import Protocol, Any, Iterable
from fractions import Fraction
from .model import Region, Floor
from .callbacks import BuildRequest, BuildReceipt, CheckRequest, CheckReceipt, FullArtifactLab, StructuralRequest, StructuralReceipt


class ArtifactFrontend(Protocol):
    def load(self, path) -> Any: ...
    def parse(self, text: str) -> Any: ...
    def serialize(self, artifact: Any) -> str | bytes: ...
    def measured(self, artifact: Any) -> dict: ...


class TaskAdapter(Protocol):
    frontend: ArtifactFrontend
    def build(self, parameters: dict, implementation: dict) -> tuple[Any, Region]: ...
    def reference(self, values: dict[str, int], scale: dict) -> tuple[dict[str, int], Fraction | int]: ...
    def lab_domain(self, parameters: dict) -> Iterable[dict[str, int]]: ...
    def measure(self, artifact: Any, parameters: dict, domain: dict) -> dict: ...
    def oracle(self, artifact: Any, parameters: dict, domain: dict) -> dict: ...
    def verify(self, artifact: Any, parameters: dict, domain: dict) -> dict: ...
    def ledger(self, artifact: Any, tree: Region) -> dict: ...
    def floors(self, tree: Region) -> list[Floor]: ...


class BuildCallback(Protocol):
    def __call__(self, request: BuildRequest) -> BuildReceipt: ...


class CheckCallback(Protocol):
    def __call__(self, request: CheckRequest) -> CheckReceipt: ...

class StructuralCallback(Protocol):
    def __call__(self, request: StructuralRequest) -> StructuralReceipt: ...


